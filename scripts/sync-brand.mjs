#!/usr/bin/env node
// Copy the locked bigd. brand kit (BigDApps/brand, its own local repo) into bigd-shared/brand/.
//
//   node scripts/sync-brand.mjs [--from ../brand]
//
// Why a copy: the kit repo has no remote and is gitignored by peanuts-lab, so Cloudflare's
// Git-connected builds can't reach it. bigd-shared is a public git dependency every app
// already installs, so it carries the kit's built outputs and the apps import them from
// node_modules/bigd-shared/brand. Never edit the copies here: change the kit's tokens.json,
// rebuild the kit, then re-run this script and bump the bigd-shared tag.

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const argFrom = process.argv.indexOf('--from')
const kit = resolve(argFrom > -1 ? process.argv[argFrom + 1] : join(root, '..', 'brand'))
const out = join(root, 'brand')

if (!existsSync(join(kit, 'tokens', 'tokens.json'))) {
  console.error(`No brand kit at ${kit} (expected tokens/tokens.json). Pass --from <kit dir>.`)
  process.exit(1)
}

// Only the generated outputs apps need. Everything else (explorations, guide, tools) stays in the kit.
const COPY = [
  ['tokens/tokens.css', 'tokens.css'],
  ['tokens/tokens.json', 'tokens.json'],
  ['tokens/tailwind.preset.js', 'tailwind.preset.js'],
  ['tokens/bigd-mark.js', 'bigd-mark.js'],
  ['fonts', 'fonts'],
  ['icons', 'icons'],
]

for (const [, dest] of COPY) rmSync(join(out, dest), { recursive: true, force: true })
mkdirSync(out, { recursive: true })
for (const [src, dest] of COPY) cpSync(join(kit, src), join(out, dest), { recursive: true })

// Logos: SVGs only (the PNG lockups are for documents, not the apps).
rmSync(join(out, 'logo'), { recursive: true, force: true })
mkdirSync(join(out, 'logo'))
for (const f of readdirSync(join(kit, 'logo'))) {
  if (f.endsWith('.svg')) cpSync(join(kit, 'logo', f), join(out, 'logo', f))
}

// Inline lockup for the shared Header: logo/lockup.svg with ink swapped for currentColor, so
// CSS (ink on light grounds, bone on dark) picks between lockup.svg and lockup-reversed.svg.
const lockup = readFileSync(join(kit, 'logo', 'lockup.svg'), 'utf8')
  .trim()
  .replaceAll('fill="#0b0b0c"', 'fill="currentColor"')
  .replace(/ width="[^"]*" height="[^"]*"/, '')
writeFileSync(
  join(out, 'lockup.js'),
  `// GENERATED by scripts/sync-brand.mjs from the kit's logo/lockup.svg. Do not edit.\n` +
    `// Ink fills are currentColor: set color to ink (light ground) or bone (dark ground).\n` +
    `export const LOCKUP_SVG = ${JSON.stringify(lockup)}\n`,
)

let sha = 'unknown'
try {
  sha = execFileSync('git', ['-C', kit, 'log', '-1', '--format=%h %cs %s'], { encoding: 'utf8' }).trim()
} catch {}
writeFileSync(
  join(out, 'KIT_VERSION'),
  `Copied from the bigd. brand kit (BigDApps/brand) by scripts/sync-brand.mjs. Do not edit.\nkit commit: ${sha}\n`,
)
console.log(`Synced brand kit -> ${out}\nkit commit: ${sha}`)
